def rows():
    lines = TABLE.read_text('ascii').splitlines()
    return [line.split('\t') for line in lines[1:]]


def decode_plan(raw):
    magic, stages, count, outputs = struct.unpack_from('<8s3Q', raw)
    if magic != b'HIASTP01':
        raise ValueError('wrong stage plan magic')
    at, records = 32, []
    for _ in range(count):
        kind, stage, fields = struct.unpack_from('<3Q', raw, at)
        at += 24
        values = []
        for _ in range(fields):
            size, = struct.unpack_from('<Q', raw, at)
            at += 8
            value = raw[at:at + size]
            if len(value) != size:
                raise ValueError('truncated plan')
            values.append(value.decode('ascii'))
            at += size
        records.append((kind, stage, values))
    if at != len(raw):
        raise ValueError('trailing plan bytes')
    return stages, outputs, records


def frame_request(stage, operation, ordinal, parts, *, auxiliary=0):
    return (struct.pack('<8s5Q', b'HIASTF01', stage, operation, ordinal, auxiliary, len(parts))
            + b''.join(struct.pack('<Q', len(part)) + part for part in parts))



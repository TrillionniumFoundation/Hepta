class ReleaseStageSourceTests(unittest.TestCase):
    def test_checked_hia_and_real_source_paths(self):
        verify_program(assemble_program(POLICY.read_bytes()).as_dict())
        for row in rows():
            if row[0] == 'compile':
                self.assertTrue((SOURCES / row[4]).is_file(), row)
            elif row[0] == 'kit':
                for name in row[2:]:
                    self.assertTrue((SOURCES / name).is_file(), row)
            elif row[0] == 'resource':
                self.assertTrue((ROOT / row[2]).is_file(), row)

    def test_all_outputs_match_current_stage_declarations(self):
        from tools.build_hia_core_edit import PROGRAMS
        from tools.build_hia_worker_release import INSTALLED_HELPERS
        from tools.build_hia_json_preflight import CANDIDATES
        from tools.build_hia_sqlite_components import UNITS, PROJECTION
        from tools.build_hia_agent_artifact_capture import UNIT
        from tools.build_hia_agent_store import PLAN
        plan = json.loads((ROOT / PLAN).read_text())
        expected = {
            1: ['hia-safe-core-prove'], 2: ['hia-nominal-constructor'],
            3: [*(name for name, _ in PROGRAMS.values()), 'hia-worker-scalar-implementation'],
            4: [name for kind in INSTALLED_HELPERS
                for name in (kind + '-manifest.json', CANDIDATES[kind][1] + '.image.bin')],
            5: [*(f"module-{group['role']}.bin" for group in plan['modules']), 'hia-agent-store'],
            6: ['hia-native'], 7: ['hia-agent-read-carrier'], 8: ['hia-owned-reference-wire'],
            9: [*('hia-' + unit for unit in (*UNITS, UNIT, 'nominal-packet')),
                'hia-' + PROJECTION, 'hia-sqlite-pager'],
            10: ['hia-sqlite-migration-publish', 'hia-sqlite-migrate'],
        }
        actual = {stage: [r[2] for r in rows() if r[:2] == ['output', str(stage)]]
                  for stage in range(1, 11)}
        self.assertEqual(actual, expected)
        self.assertEqual(sum(map(len, actual.values())), 66)

    def test_declared_ordered_constructor_and_helper_groups(self):
        from tools.build_hia_nominal_constructor import COMPONENTS, CONSTRUCTOR_IMAGES
        from tools.build_hia_worker_release import INSTALLED_HELPERS
        from tools.build_hia_json_preflight import CANDIDATES
        constructor = [(Path(COMPONENTS[key]).name,
                        COMPONENTS[key].removeprefix('examples/hia_bootstrap/'))
                       for key in CONSTRUCTOR_IMAGES]
        helpers = [(CANDIDATES[kind][0] + '.hepta',) * 2 for kind in INSTALLED_HELPERS]
        for stage, group, expected in ((2, 'constructor', constructor), (4, 'helpers', helpers)):
            actual = [tuple(r[3:]) for r in rows() if r[:3] == ['compile', str(stage), group]]
            self.assertEqual(actual, expected)


@unittest.skipUnless(os.environ.get('HIA_TEST_RELEASE_STAGE_PLANNER'),
                     'requires the source-compiled native stage planner')
class ReleaseStageNativeTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.planner = Path(os.environ['HIA_TEST_RELEASE_STAGE_PLANNER']).resolve()

    def invoke(self, data, *, refused=False):
        p = subprocess.run([str(self.planner), 'build'], input=data, capture_output=True,
                           env={'PATH': ''}, timeout=30)
        self.assertEqual(p.stderr, b'')
        if refused:
            self.assertNotEqual(p.returncode, 0)
            self.assertEqual(p.stdout, b'')
        else:
            self.assertEqual(p.returncode, 0)
        return p.stdout

    def test_complete_native_plan_matches_every_declared_record(self):
        stages, outputs, records = decode_plan(self.invoke(TABLE.read_bytes()))
        self.assertEqual((stages, outputs), (10, 66))
        expected = [(KINDS[r[0]], int(r[1]), r[2:]) for r in rows()]
        self.assertEqual(records, expected)

    def test_malformed_plans_publish_nothing(self):
        valid = TABLE.read_bytes()
        lines = valid.splitlines(keepends=True)
        duplicate = next(line for line in lines if line.startswith(b'compile\t2\t'))
        invalid = (
            valid[:-1], valid + b'\0', valid.replace(b'HIASTG01\t', b'HIASTG01x\t', 1),
            valid.replace(b'\t10\t66\n', b'\t10\t65\n', 1),
            valid.replace(b'stage\t2\t', b'stage\t3\t', 1),
            valid.replace(b'need\t3\t1\thia-safe-core-prove', b'need\t3\t4\thia-safe-core-prove', 1),
            valid.replace(b'need\t3\t1\thia-safe-core-prove', b'need\t3\t1\thia-missing', 1),
            valid.replace(b'output\t2\thia-nominal-constructor', b'output\t2\thia-safe-core-prove', 1),
            valid.replace(duplicate, duplicate + duplicate, 1),
            valid.replace(b'\tcomposite_constructor_owner.hepta\n',
                          b'\t../composite_constructor_owner.hepta\n', 1),
            valid.replace(b'kit\t1\t', b'unknown\t1\t', 1),
        )
        for wire in invalid:
            with self.subTest(sha256=sha256(wire).hexdigest()):
                self.invoke(wire, refused=True)

    def test_all_thirty_native_frame_operations_match_existing_wire_abis(self):
        seen = set()
        for stage, op, ordinal, count, magic, layout in FRAME_CASES:
            seen.add((stage, op))
            parts = [bytes([65 + i % 26]) * (i + 3) for i in range(count)]
            if layout == 'pinned':
                parts[1] = sha256(parts[0]).digest()
            if layout == 'ordinal':
                expected = struct.pack('<8sQQ', magic, ordinal, len(parts[0])) + parts[0]
            elif layout == 'helper':
                expected = struct.pack('<8s5Q', magic, ordinal, *map(len, parts)) + b''.join(parts)
            elif layout == 'store':
                expected = (struct.pack('<8s3Q', magic, ordinal, len(parts[0]), count - 1)
                            + struct.pack('<' + 'Q' * (count - 1), *map(len, parts[1:]))
                            + b''.join(parts))
            elif layout == 'pinned':
                expected = struct.pack('<8sQQ', magic, ordinal, len(parts[0])) + parts[1] + parts[0]
            else:
                expected = struct.pack('<8s' + 'Q' * count, magic, *map(len, parts)) + b''.join(parts)
            with self.subTest(stage=stage, operation=op, ordinal=ordinal):
                self.assertEqual(self.invoke(frame_request(stage, op, ordinal, parts)), expected)
                self.invoke(frame_request(stage, op, ordinal, parts, auxiliary=1), refused=True)
        self.assertEqual(len(seen), 30)

    def test_unknown_roles_and_incomplete_frames_publish_nothing(self):
        valid = frame_request(4, 1, 1, [b'source', b'image', b'selfhost', b'compiler'])
        for wire in (valid[:-1], valid + b'x', valid[:48] + struct.pack('<Q', (1 << 64) - 1),
                     frame_request(4, 1, 0, [b'x'] * 4), frame_request(4, 1, 9, [b'x'] * 4),
                     frame_request(3, 1, 0, [b'x']), frame_request(1, 1, 0, [b'x']),
                     frame_request(10, 3, 19, [b'x', b'y' * 32]),
                     frame_request(10, 3, 20, [b'x', b'y' * 31]),
                     frame_request(5, 2, 0, [b'x'] * 6), frame_request(9, 9, 0, [b'x'] * 11)):
            with self.subTest(sha256=sha256(wire).hexdigest()):
                self.invoke(wire, refused=True)


@unittest.skipUnless(os.environ.get('HIA_TEST_RELEASE_STAGE_PLANNER')
                     and os.environ.get('HIA_TEST_NATIVE_SOURCE_SEED'),
                     'requires native planner and a source build seed')
class ReleaseStageConsumerTests(unittest.TestCase):
    invoke = ReleaseStageNativeTests.invoke
    @classmethod
    def setUpClass(cls):
        cls.planner = Path(os.environ['HIA_TEST_RELEASE_STAGE_PLANNER']).resolve()
        cls.seed = Path(os.environ['HIA_TEST_NATIVE_SOURCE_SEED']).resolve()
        cls.temporary = TemporaryDirectory(prefix='release-stage-consumers-')
        cls.addClassCleanup(cls.temporary.cleanup)
        cls.work = Path(cls.temporary.name)
        cls.kits = {}

    def native(self, program, operation, data):
        p = subprocess.run([str(program), operation], input=data, capture_output=True,
                           env={'PATH': ''}, timeout=180)
        self.assertEqual((p.returncode, p.stderr), (0, b''))
        return p.stdout

    def compile(self, named):
        from tools.build_hia_source_build import _named_source_request, _compiled_sources
        wire = self.native(self.seed, 'sources', _named_source_request(named))
        return wire, _compiled_sources(wire, named)

    def kit(self, policy, application):
        key = (policy, application)
        if key not in self.kits:
            sources = {'source_build_policy.hepta': (SOURCES / policy).read_bytes(),
                       'source_build_packer.hepta': (SOURCES / application).read_bytes(),
                       'selfhost.hepta': (SOURCES / 'selfhost.hepta').read_bytes()}
            wire, images = self.compile(sources)
            raw = self.native(self.seed, 'pack', wire)
            self.assertEqual(raw[:4], b'\x7fELF')
            path = self.work / ('kit-' + str(len(self.kits)))
            path.write_bytes(raw)
            path.chmod(0o500)
            self.kits[key] = path, images
        return self.kits[key]

    def test_generated_helper_frame_is_accepted_by_real_hia_manifest_owner(self):
        from tools.build_hia_json_preflight import _image_manifest
        owner, kit_images = self.kit('source_helper_manifest.hepta', 'source_build_packer.hepta')
        source = (SOURCES / 'agent_schema.hepta').read_bytes()
        _, images = self.compile({'agent_schema.hepta': source})
        image = images['agent_schema.hepta']
        compiler = kit_images['selfhost.hepta']
        parts = [source, image, (SOURCES / 'selfhost.hepta').read_bytes(), compiler]
        framed = self.invoke(frame_request(4, 1, 1, parts))
        raw = self.native(owner, 'build', framed)
        expected = _image_manifest('agent-schema', 'agent-schema', source, image,
                                   'agent-schema.image.bin', sha256(compiler).hexdigest())
        self.assertEqual(json.loads(raw), expected)

    def test_generated_sqlite_frame_is_accepted_by_real_hia_embed_owner(self):
        owner, _ = self.kit('source_sqlite_unit.hepta', 'elf_embed_image.hepta')
        source = (SOURCES / 'sqlite_rowid_lookup.hepta').read_bytes()
        _, images = self.compile({'lookup.hepta': source})
        obj = self.native(owner, 'build', self.invoke(frame_request(9, 2, 1, [source])))
        self.assertEqual(obj[:4], b'\x7fELF')
        self.assertEqual(struct.unpack_from('<H', obj, 16)[0], 1)
        self.assertIn(images['lookup.hepta'], obj)

    def test_generated_store_frame_is_accepted_by_real_hia_word_filter(self):
        from tools.build_hia_agent_store import PLAN, PROGRAMS
        plan_bytes = (ROOT / PLAN).read_bytes()
        plan = json.loads(plan_bytes)
        spec = next(v for v in plan['units'].values() if v.get('id') == 0)
        source = (ROOT / (PROGRAMS + spec['source'])).read_bytes()
        _, images = self.compile({'unit.hepta': source})
        owner, _ = self.kit('source_agent_store.hepta', 'agent_store/word_filter.hepta')
        output = self.native(owner, 'build',
                             self.invoke(frame_request(5, 1, 0, [plan_bytes, images['unit.hepta']])))
        self.assertTrue(output)
        self.assertEqual(len(output), spec['image_bytes'])
        self.assertEqual(sha256(output).hexdigest(), spec['image_sha256'])


if __name__ == '__main__':
    unittest.main()

"""P5 negative-controls for untrusted, bounded HIA edit-context renderers.

Presentation is not program admission. Malformed queries must fail with the
public HIAEditRejected protocol instead of leaking arbitrary Python exceptions
or displaying forged noninteger batch site IDs.
"""
from __future__ import annotations

import copy
import unittest

from hepta.hia_edit_query import prepare_edit, render_edit_context
from hepta.hia_edit_batch import prepare_batch, render_batch_context
from hepta.hia_program_tools import HIAEditRejected
from tests.test_hia_edit_transitive_context import chain


class RenderInputBoundaryTests(unittest.TestCase):
    def test_real_prepared_edits_and_batch_render_still_work(self):
        program = chain()
        selection = {"function": "work", "block": "entry", "output": "first",
                     "fields": ["op"]}
        single = prepare_edit(program, **selection)
        display = render_edit_context(single)
        self.assertIn("EDIT %first:u32", display)
        batch = prepare_batch(program, [selection])
        rendered = render_batch_context(batch)
        self.assertIn("@0{op}", rendered)

    def test_malformed_single_query_fails_closed(self):
        program = chain()
        valid = prepare_edit(program, function="work", block="entry",
                             output="first", fields=["op"])
        for field, replacement in (
            ("context", []), ("context", {"function": []}),
            ("selector", []), ("unexpected", True),
        ):
            with self.subTest(field=field, replacement=replacement):
                query = copy.deepcopy(valid)
                query[field] = replacement
                with self.assertRaises(HIAEditRejected):
                    render_edit_context(query)
        corrupt = copy.deepcopy(valid)
        corrupt["context"]["dependencies"] = [{"index": 0, "operation": None}]
        with self.assertRaises(HIAEditRejected):
            render_edit_context(corrupt)
        with self.assertRaises(HIAEditRejected):
            render_edit_context(["not a query"])

    def test_malformed_batch_sites_and_noninteger_aliases_refused(self):
        program = chain()
        valid = prepare_batch(program, [{"function": "work", "block": "entry",
                                         "output": "first", "fields": ["op"]}])
        cases = []
        for forged in (True, 0.0, -1, "0", 1):
            candidate = copy.deepcopy(valid)
            candidate["sites"][0]["site"] = forged
            cases.append(candidate)
        for replacement in ([], None, 42, {"query": {}}, {"site": 0, "query": []},
                            {"site": 0, "query": {"context": []}}):
            candidate = copy.deepcopy(valid)
            candidate["sites"][0] = replacement
            cases.append(candidate)
        candidate = copy.deepcopy(valid)
        candidate["sites"][0]["query"]["context"]["function"] = 9
        cases.append(candidate)
        candidate = copy.deepcopy(valid)
        candidate["rogue"] = "text not generated by prepare_batch"
        cases.append(candidate)
        for index, query in enumerate(cases):
            with self.subTest(case=index), self.assertRaises(HIAEditRejected):
                render_batch_context(query)

    def test_bounded_wire_rejection_is_preserved_in_both_renderers(self):
        program = chain()
        single = prepare_edit(program, function="work", block="entry",
                              output="first", fields=["op"])
        single["context"]["injected"] = "X" * (1024 * 1024 + 1)
        with self.assertRaises(HIAEditRejected):
            render_edit_context(single)
        batch = prepare_batch(program, [{"function": "work", "block": "entry",
                                         "output": "first", "fields": ["op"]}])
        batch["sites"][0]["query"]["context"]["injected"] = "X" * (1024 * 1024 + 1)
        with self.assertRaises(HIAEditRejected):
            render_batch_context(batch)


if __name__ == "__main__":
    unittest.main()

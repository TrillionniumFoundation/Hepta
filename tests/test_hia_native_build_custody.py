"""Publication refuses a compiler/packer swapped and restored during a build.

These are rejection-only fixtures. Native execution is mocked at its boundary;
no synthetic cold record is written or used as qualification evidence.
"""
from contextlib import ExitStack
from hashlib import sha256
import importlib
import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch


CHECKS = ('export_manifest_matches_qualification', 'isolated_python_without_site',
    'nested_full_qualification_pass', 'nested_process_exit_zero',
    'no_ancestor_git_identity', 'no_bytecode_cache_created',
    'no_inherited_home_or_python_cache', 'no_inherited_seed_or_successor_images',
    'origin_hashes_preserved', 'owned_process_tree_cleanup_confirmed',
    'source_export_hashes_preserved')


def digest(value):
    return sha256(value).hexdigest()


def compile_receipt(compiler, source, image):
    return {'artifact_sha256': digest(compiler), 'input_sha256': digest(source),
            'source_sha256': digest(source), 'produced_sha256': digest(image)}


def emission_receipt(image, source, output, size):
    return {'status': 'returned', 'abi_status': 0, 'core_u32': size,
            'source_unchanged': True, 'forbidden_compiler_modules_loaded': [],
            'artifact_sha256': digest(image), 'image_sha256': digest(image),
            'input_sha256': digest(source), 'source_sha256': digest(source),
            'output_sha256': digest(output)}


class NativeBuildCustodyTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='hia-build-custody-')
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.source_dir = self.root / 'examples/hia_bootstrap'
        self.source_dir.mkdir(parents=True)
        self.compiler = self.root / 'compiler.bin'
        self.compiler_bytes = b'rejection-only compiler, never executed'
        self.compiler.write_bytes(self.compiler_bytes)
        self.cold = self.root / 'cold.json'
        self.cold.write_bytes(b'{"status":"REJECTION_ONLY_FIXTURE"}\n')
        self.gate = {'schema': 'hepta.hia.selfhost-cold-replay.v1',
            'status': 'COLD_SELFHOST_REPLAY_PASS', 'returncode': 0,
            'checks': dict.fromkeys(CHECKS, True),
            'generation_sha256': [digest(self.compiler_bytes)] * 3}

    def test_json_and_sha_builders_refuse_transient_compiler_and_output_substitution(self):
        cases = (('build_hia_json_preflight', 'preflight', 'json_preflight'),
                 ('build_hia_json_preflight', 'decode', 'json_decode'),
                 ('build_hia_json_preflight', 'canonical', 'json_canonical'),
                 ('build_hia_json_preflight', 'core-frontend', 'core_json_frontend'),
                 ('build_hia_sha256', 'sha256', 'sha256'),
                 ('build_hia_sha256', 'sha256_stream', 'sha256_stream'))
        for module_name, candidate, source_name in cases:
            module = importlib.import_module('tools.' + module_name)
            (self.source_dir / (source_name + '.hiaasm')).write_bytes(b'rejection-only source')
            for variant in ('compiler-aba', 'input', 'source', 'output', 'missing-produced'):
                destination = self.root / (source_name + '-' + variant)
                with self.subTest(candidate=candidate, variant=variant):
                    def stage(output, label, selected_compiler, source):
                        image = b'rejection-only generated bytes'
                        path = output / 'candidate.bin'
                        path.write_bytes(image)
                        receipt = compile_receipt(self.compiler_bytes, source, image)
                        if variant == 'compiler-aba':
                            selected_compiler.write_bytes(b'different compiler during invocation')
                            receipt['artifact_sha256'] = digest(selected_compiler.read_bytes())
                            selected_compiler.write_bytes(self.compiler_bytes)
                        elif variant == 'input':
                            receipt['input_sha256'] = digest(source + b'changed')
                        elif variant == 'source':
                            receipt['source_sha256'] = digest(source + b'changed')
                        elif variant == 'output':
                            path.write_bytes(image + b'changed after invocation')
                        else:
                            del receipt['produced_sha256']
                        return path, receipt

                    with patch.object(module, 'ROOT', self.root), patch.object(
                            module.json, 'loads', return_value=self.gate), patch(
                            'tools.qualify_hia_selfhost.compile_stage', side_effect=stage):
                        with self.assertRaisesRegex(ValueError, 'receipt identity mismatch'):
                            module.build(destination, self.compiler, self.cold, candidate=candidate)
                    self.assertEqual(self.compiler.read_bytes(), self.compiler_bytes)
                    self.assertFalse((destination / 'manifest.json').exists())
                    self.assertFalse((destination / 'build.json').exists())

    def test_json_and_sha_builders_refuse_changed_cold_evidence(self):
        for module_name, source_name in (('build_hia_json_preflight', 'json_preflight'),
                                          ('build_hia_sha256', 'sha256')):
            module = importlib.import_module('tools.' + module_name)
            (self.source_dir / (source_name + '.hiaasm')).write_bytes(b'rejection-only source')
            destination = self.root / (source_name + '-cold-drift')

            def stage(output, label, selected_compiler, source):
                image = b'candidate'
                path = output / 'candidate.bin'
                path.write_bytes(image)
                self.cold.write_bytes(self.cold.read_bytes() + b'changed')
                return path, compile_receipt(self.compiler_bytes, source, image)

            with self.subTest(component=module_name), patch.object(module, 'ROOT', self.root), patch.object(
                    module.json, 'loads', return_value=self.gate), patch(
                    'tools.qualify_hia_selfhost.compile_stage', side_effect=stage):
                with self.assertRaisesRegex(ValueError, 'build inputs changed'):
                    module.build(destination, self.compiler, self.cold)
            self.assertFalse((destination / 'manifest.json').exists())

    def test_emission_requires_actual_packer_frame_and_complete_output(self):
        from tools.build_hia_source_lexer import _checked_native_emission
        image, source, output = b'packer', b'frame', b'ELF-prefix' + b'\xa5' * 3
        receipt = emission_receipt(image, source, output, 10)
        self.assertEqual(_checked_native_emission(receipt, image, source, output), b'ELF-prefix')
        mutations = ({'artifact_sha256': digest(b'temporary packer')},
            {'image_sha256': digest(b'temporary packer')}, {'input_sha256': digest(b'wrong frame')},
            {'source_sha256': digest(b'wrong frame')}, {'source_unchanged': False},
            {'status': 'timeout'}, {'abi_status': True}, {'core_u32': True},
            {'core_u32': len(output) + 1}, {'core_u32': 0},
            {'output_sha256': digest(output[:10])}, {'forbidden_compiler_modules_loaded': ['hepta.parser']})
        for mutation in mutations:
            with self.subTest(mutation=mutation), self.assertRaisesRegex(ValueError, 'receipt identity mismatch'):
                _checked_native_emission({**receipt, **mutation}, image, source, output)
        with self.assertRaisesRegex(ValueError, 'receipt identity mismatch'):
            _checked_native_emission(receipt, image, source, output[:-1])

    def _cli_fixtures(self, variant):
        from tools import build_hia_core_json_cli as module
        source = self.source_dir / 'core_json_cli_packer.hiaasm'
        source.write_bytes(b'rejection-only packer source')
        frontend_source = self.source_dir / 'core_json_frontend.hiaasm'
        frontend_source.write_bytes(b'rejection-only frontend source')

        def frontend(output, compiler, cold, **kwargs):
            output.mkdir()
            image = output / 'frontend.bin'
            image.write_bytes(b'captured frontend')
            manifest = {'image_path': image.name, 'image_sha256': digest(image.read_bytes()),
                        'compiler_sha256': digest(self.compiler_bytes),
                        'source_sha256': digest(frontend_source.read_bytes())}
            if variant == 'frontend-compiler':
                manifest['compiler_sha256'] = digest(b'transient compiler')
            if variant == 'frontend-source':
                manifest['source_sha256'] = digest(b'transient frontend source')
            path = output / 'manifest.json'
            path.write_text(json.dumps(manifest))
            cold_raw = cold.read_bytes()
            admitted_cold = cold_raw
            if variant == 'cold-aba':
                cold.write_bytes(b'temporary different cold evidence')
                admitted_cold = cold.read_bytes()
                cold.write_bytes(cold_raw)
            (output / 'build.json').write_text(json.dumps({
                'status': 'NATIVE_CANDIDATE_BUILT', 'manifest': manifest,
                'cold_report_sha256': digest(admitted_cold)}))
            return path

        def stage(output, label, compiler, source):
            image = b'captured packer'
            path = output / 'packer.bin'
            path.write_bytes(image)
            receipt = compile_receipt(self.compiler_bytes, source, image)
            if variant == 'compile-aba':
                compiler.write_bytes(b'transient compiler')
                receipt['artifact_sha256'] = digest(compiler.read_bytes())
                compiler.write_bytes(self.compiler_bytes)
            return path, receipt

        def invoke(output, label, packer, frame):
            packed = b'not executed ELF data'
            receipt = emission_receipt(packer.read_bytes(), frame, packed, len(packed))
            if variant == 'packer-aba':
                original = packer.read_bytes()
                packer.write_bytes(b'transient packer')
                receipt['artifact_sha256'] = receipt['image_sha256'] = digest(packer.read_bytes())
                packer.write_bytes(original)
            elif variant == 'frame':
                receipt['input_sha256'] = digest(frame + b'substitution')
            else:
                receipt['output_sha256'] = digest(packed + b'substitution')
            return receipt, packed

        stack = ExitStack()
        stack.enter_context(patch.object(module, 'ROOT', self.root))
        stack.enter_context(patch.object(module, 'SOURCE', source))
        stack.enter_context(patch.object(module, 'build_frontend', side_effect=frontend))
        stack.enter_context(patch.object(module, 'compile_stage', side_effect=stage))
        stack.enter_context(patch.object(module, 'invoke', side_effect=invoke))
        return module, stack

    def test_cli_cannot_publish_a_mixed_frontend_compiler_or_packer(self):
        for variant in ('frontend-compiler', 'frontend-source', 'cold-aba', 'compile-aba', 'packer-aba', 'frame', 'output'):
            module, stack = self._cli_fixtures(variant)
            destination = self.root / ('cli-' + variant)
            with self.subTest(variant=variant), stack:
                with self.assertRaisesRegex(ValueError, 'identity mismatch'):
                    module.build(destination, self.compiler, self.cold)
            self.assertFalse((destination / 'hia-core-json').exists())
            self.assertFalse((destination / 'build.json').exists())

    def test_observer_reference_must_name_the_actual_packer_source_before_compilation(self):
        from tools import hia_selfhost_native_observer as module
        source = self.root / 'observer.hiaasm'
        source.write_bytes(b'changed source after independent reference')
        reference = {'before_B0': True, 'packer_source_sha256': digest(b'original source')}
        with patch.object(module, 'PACKER', source), patch('tools.qualify_hia_selfhost.compile_stage') as compile_:
            with self.assertRaisesRegex(ValueError, 'reference source identity mismatch'):
                module.build(self.root, self.compiler, reference)
        compile_.assert_not_called()
        self.assertFalse((self.root / 'native-observer.elf').exists())

    def test_observer_refuses_transient_compiler_or_packer_before_publication(self):
        from tools import hia_selfhost_native_observer as module
        source = self.root / 'observer.hiaasm'
        source.write_bytes(b'captured observer source')
        emitted = b'never executed observer ELF'
        reference = {'before_B0': True, 'packer_source_sha256': digest(source.read_bytes()),
                     'expected_image_bytes': len(emitted), 'expected_image_sha256': digest(emitted)}
        for variant in ('compiler', 'packer', 'output'):
            destination = self.root / ('observer-' + variant)
            destination.mkdir()

            def stage(output, label, compiler, source):
                image = b'captured observer packer'
                path = output / 'packer.bin'
                path.write_bytes(image)
                receipt = compile_receipt(self.compiler_bytes, source, image)
                if variant == 'compiler':
                    compiler.write_bytes(b'transient compiler')
                    receipt['artifact_sha256'] = digest(compiler.read_bytes())
                    compiler.write_bytes(self.compiler_bytes)
                return path, receipt

            def invoke(output, label, packer, frame):
                receipt = emission_receipt(packer.read_bytes(), frame, emitted, len(emitted))
                if variant == 'packer':
                    original = packer.read_bytes()
                    packer.write_bytes(b'transient packer')
                    receipt['artifact_sha256'] = receipt['image_sha256'] = digest(packer.read_bytes())
                    packer.write_bytes(original)
                else:
                    receipt['output_sha256'] = digest(emitted + b'changed')
                return receipt, emitted

            with self.subTest(variant=variant), patch.object(module, 'PACKER', source), patch(
                    'tools.qualify_hia_selfhost.compile_stage', side_effect=stage), patch(
                    'tools.qualify_hia_selfhost.invoke', side_effect=invoke):
                with self.assertRaisesRegex(ValueError, 'receipt identity mismatch'):
                    module.build(destination, self.compiler, reference)
            self.assertFalse((destination / 'native-observer.elf').exists())
            self.assertFalse((destination / 'native-observer-build.json').exists())


if __name__ == '__main__':
    unittest.main()

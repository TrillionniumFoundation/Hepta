"""Emit the two complete patch policies and their fixed mechanical operands.

This is an independent explicit component. It changes no old source registry,
worker resource role, default selector, selfhost source or ordinary image.
"""
from __future__ import annotations

import argparse
from hashlib import sha256
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
if __package__ in (None, ''):
    sys.path.insert(0, str(ROOT))

from hepta.hia_agent_assembly import render_assembly
from hepta.hia_patch_result_native import HOST_SOURCE_FILES
from tools.hia_patch_result_control import compile_policy
from tools.hia_front_generator import document as _document, ports_source
from tools.generate_hia_machine_plan_control import table

ENTRIES = ('_check_patch_interface', 'apply_program_patch')
IMPORTS = {'hia_program': ('verify_program',)}
SOURCE_PATH = 'examples/hia_bootstrap/patch_result.hepta'
PORTS_PATH = 'hepta/hia_patch_result_ports.py'
DATA_PATH = 'hepta/hia_patch_result_data.py'


def program():
    return compile_policy((ROOT / 'tools/hia_patch_result_policy.py').read_text(),
                          ENTRIES, IMPORTS)


def document(policy=None):
    return _document(program() if policy is None else policy, 'patch_result')


def compatibility_data(assembly, ports):
    hosts = {}
    for name in HOST_SOURCE_FILES:
        raw = ports if name == 'hia_patch_result_ports.py' else (ROOT / 'hepta' / name).read_bytes()
        hosts[name] = sha256(raw).hexdigest()
    return ('"""Generated patch compatibility; not current-cold qualification."""\n'
            + 'SOURCE_BYTES = ' + repr(len(assembly)) + '\n'
            + 'SOURCE_SHA256 = ' + repr(sha256(assembly).hexdigest()) + '\n'
            + 'HOST_SOURCE_SHA256 = ' + repr(hosts) + '\n').encode('utf-8')


def generated():
    policy = program()
    data = table(policy)
    assembly = render_assembly(document(policy)).encode('utf-8')
    ports = ports_source(policy, data, ENTRIES, IMPORTS).encode('utf-8')
    return assembly, ports, compatibility_data(assembly, ports), policy, data


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / SOURCE_PATH)
    parser.add_argument('--ports', type=Path, default=ROOT / PORTS_PATH)
    parser.add_argument('--identity', type=Path, default=ROOT / DATA_PATH)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    assembly, ports, identity, policy, data = generated()
    outputs = ((args.output, assembly), (args.ports, ports), (args.identity, identity))
    if args.check:
        if any(path.read_bytes() != raw for path, raw in outputs):
            raise AssertionError('patch_result generated bytes differ')
    else:
        for path, raw in outputs:
            path.write_bytes(raw)
    print({'roots': len(ENTRIES), 'functions': len(policy.functions),
           'instructions': sum(len(function.instructions) for function in policy.functions),
           'table_bytes': len(data), 'table_sha256': sha256(data).hexdigest(),
           'source_sha256': sha256(assembly).hexdigest(),
           'ports_sha256': sha256(ports).hexdigest(),
           'compatibility_sha256': sha256(identity).hexdigest(),
           'scope': 'TWO_PATCH_POLICIES_WITH_REAL_FOREIGN_DEPENDENCIES',
           'prepare_engine_replaced': False, 'whole_verify_closed': False,
           'current_source_cold': False, 'default_activated': False})


if __name__ == '__main__':
    main()

"""Read original compiler-plan evidence without running another native call.

The output is descriptive paired cost accounting, never a performance pass.
All elapsed intervals remain in their original scopes. Unknown acquisition,
engineering, provider and deployment costs prevent a full amortization claim.
"""
from __future__ import annotations

import argparse
from fractions import Fraction
from hashlib import sha256
import json
import math
from pathlib import Path
import statistics

ARMS = ("canonical", "compact_immediates", "compact_swapped_scratch")
WORKLOADS = ("compiler", "sample")
SCHEMA = "hepta.hia.selfhost-paired-cost.v1"
ORIGINAL_SCHEMA = "hepta.hia.agent.selfhost-machine-plans.v1"


def require(condition, message):
    if not condition:
        raise ValueError("E_SELFHOST_PAIRED_COST: " + message)


def nonnegative(value):
    return type(value) is int and value >= 0


def digest(data):
    return sha256(data).hexdigest()


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        require(key not in result, "duplicate JSON field")
        result[key] = value
    return result


def decode(raw):
    return json.loads(raw, object_pairs_hook=unique_object,
                      parse_constant=lambda value: require(False, "non-finite JSON number"))


def schedule(repetitions):
    rows = []
    for repeat in range(repetitions):
        order = ARMS[repeat % len(ARMS):] + ARMS[:repeat % len(ARMS)]
        if repeat % 2:
            order = tuple(reversed(order))
        for workload in WORKLOADS:
            rows.extend((repeat, workload, arm) for arm in order)
    return rows


def empirical(values):
    require(bool(values) and all(type(x) is int and x > 0 for x in values),
            "positive original native times required")
    ordered = sorted(values)
    return {"count": len(values), "minimum_ns": ordered[0],
            "median_ns": statistics.median(values),
            "mean_ns": statistics.mean(values),
            "empirical_p95_ns": ordered[math.ceil(len(values) * .95) - 1],
            "maximum_ns": ordered[-1], "all_original_ns": values,
            "tail_scope": "nearest-rank empirical quantile; with seven samples p95 is the maximum; no population tail bound"}


def summarize(report):
    """Summarize a parsed original report; read_campaign adds byte validation."""
    require(report.get("schema") == ORIGINAL_SCHEMA, "original campaign schema")
    repetitions = report.get("repetitions")
    require(type(repetitions) is int and 3 <= repetitions <= 15, "registered repetition count")
    cost = report.get("campaign_cost", {})
    require(all(nonnegative(cost.get(k)) for k in
                ("wall_ns", "parent_cpu_ns", "children_cpu_ns")), "original outer costs missing")
    result = {"schema": SCHEMA, "original_status": report.get("status"),
              "checkout": report.get("checkout"), "original_campaign_cost": cost,
              "complete_paired_inventory": False, "comparisons": [],
              "observed_preparation": {}, "workloads": {},
              "missing_costs": ["source acquisition", "dependency acquisition", "Agent or human engineering",
                                "provider usage and money", "final inventory serialization and upload",
                                "production installation, future use, recovery and maintenance"],
              "cost_accounting": "outer campaign includes child, phase and build intervals; nested intervals are never added to it",
              "paired_scope": "same round, source, complete generated bytes and buffer ABI; finite observations on one shared host",
              "strong_external_baseline_measured": False,
              "general_semantic_equivalence_proved": False,
              "full_lifecycle_cost_known": False, "reproducible_speedup_established": False,
              "economic_benefit_established": False, "ndu_increment_established": False,
              "acceptance": "HOLD"}
    if report.get("status") != "passed":
        result["incomplete_reason"] = "original campaign did not pass; costs and failure retained, no paired saving inferred"
        result["original_error"] = report.get("error")
        return result
    arms = report.get("arms", {})
    require(set(arms) == set(ARMS), "complete three-arm inventory required")
    rows = report.get("native_invocations", [])
    require(type(rows) is list and all(type(x) is dict for x in rows), "native invocation inventory")
    cases = [x.get("case") for x in rows]
    require(len(cases) == len(set(cases)), "duplicate native invocation")
    require(all(x.get("status") == "returned" and x.get("abi_status") == 0
                and x.get("source_unchanged") is True for x in rows), "failed native call in passing report")
    scheduled = schedule(repetitions)
    labels = [f"compile-{workload}-r{repeat}-{arm}" for repeat, workload, arm in scheduled]
    require(cases[:len(labels)] == labels, "original measured order or pair inventory changed")
    require(len(rows) == len(labels) + 39, "original finite-control inventory incomplete")
    phases = report.get("phases", [])
    phase_names = [x.get("label") for x in phases]
    require(len(phase_names) == len(set(phase_names)), "duplicate phase")
    by_phase = dict(zip(phase_names, phases))
    for phase in phases:
        require(phase.get("status") == "completed" and
                all(nonnegative(phase.get(k)) for k in
                    ("wall_ns", "parent_cpu_ns", "children_cpu_ns", "started_monotonic_ns", "finished_monotonic_ns")),
                "incomplete measured phase")
        require(phase["wall_ns"] == phase["finished_monotonic_ns"] - phase["started_monotonic_ns"],
                "phase wall interval mismatch")
    timings = {(workload, arm): [] for workload in WORKLOADS for arm in ARMS}
    outputs = {}
    for (repeat, workload, arm), row in zip(scheduled, rows):
        timing = row.get("native_elapsed_ns")
        require(type(timing) is int and timing > 0 and nonnegative(row.get("wall_elapsed_ns"))
                and timing <= row["wall_elapsed_ns"], "native interval exceeds complete invocation")
        phase = by_phase.get("native/" + row["case"], {})
        require(nonnegative(phase.get("wall_ns")) and row["wall_elapsed_ns"] <= phase["wall_ns"],
                "invocation exceeds charged phase")
        require(row.get("input_sha256") == report["workload"][workload]["sha256"]
                and row.get("source_sha256") == row["input_sha256"], "measured inputs differ")
        require(row.get("artifact_sha256") == arms[arm]["shared_sha256"]
                and row.get("image_sha256") == row["artifact_sha256"], "arm image binding differs")
        output = row.get("core_u32"), row.get("output_sha256"), row.get("produced_sha256")
        require(type(output[0]) is int and output[0] > 0 and
                all(type(v) is str and len(v) == 64 for v in output[1:]), "produced-image identity absent")
        require(workload not in outputs or outputs[workload] == output, "complete output bytes differ across paired arms")
        outputs[workload] = output
        timings[workload, arm].append(timing)
    for arm in ARMS:
        for workload in WORKLOADS:
            require(arms[arm]["timings_ns"][workload] == timings[workload, arm], "summary does not match original scheduled calls")
        selected = [by_phase.get(prefix + arm, {}) for prefix in ("emit/", "rederive_link/")]
        require(all(x.get("status") == "completed" for x in selected), "preparation phase absent")
        result["observed_preparation"][arm] = {
            k: sum(x[k] for x in selected) for k in ("wall_ns", "parent_cpu_ns", "children_cpu_ns")}
        result["observed_preparation"][arm]["scope"] = "emit plus rederive/link/recheck; common registration and all other lifecycle costs excluded"
    common = by_phase.get("source_and_core_registration")
    require(common is not None, "common source and plan registration absent")
    result["common_registration"] = {k: common[k] for k in ("wall_ns", "parent_cpu_ns", "children_cpu_ns")}
    for workload in WORKLOADS:
        result["workloads"][workload] = {arm: empirical(timings[workload, arm]) for arm in ARMS}
        base = timings[workload, "canonical"]
        for arm in ARMS[1:]:
            candidate = timings[workload, arm]
            savings = [a - b for a, b in zip(base, candidate)]
            ratios = [float(Fraction(b, a)) for a, b in zip(base, candidate)]
            saved = statistics.median(savings)
            extra = result["observed_preparation"][arm]["wall_ns"] - result["observed_preparation"]["canonical"]["wall_ns"]
            result["comparisons"].append({
                "workload": workload, "candidate": arm, "baseline": "canonical",
                "pairs": [{"repeat": n, "baseline_native_ns": a, "candidate_native_ns": b,
                           "baseline_minus_candidate_ns": a - b, "candidate_over_baseline": float(Fraction(b, a))}
                          for n, (a, b) in enumerate(zip(base, candidate))],
                "median_paired_saving_ns": saved, "mean_paired_saving_ns": statistics.mean(savings),
                "positive_saving_pairs": sum(x > 0 for x in savings),
                "median_paired_ratio": statistics.median(ratios),
                "empirical_p95_ratio": result["workloads"][workload][arm]["empirical_p95_ns"] /
                                       result["workloads"][workload]["canonical"]["empirical_p95_ns"],
                "extra_observed_emit_link_wall_ns": extra,
                "conditional_observed_break_even_calls": math.ceil(max(0, extra) / saved) if saved > 0 else None,
                "break_even_scope": "point arithmetic for measured emit/link difference and median paired saving only; assumes repeated identical workload; not a full-cost or guaranteed break-even",
                "full_lifecycle_break_even_calls": None,
                "population_inference": "none; fixed deterministic order and repeated shared-host observations"})
    result["complete_paired_inventory"] = True
    return result


def read_campaign(directory, expected_sealed_sha256):
    directory = Path(directory).resolve(strict=True)
    raw = (directory / "SEALED.json").read_bytes()
    require(digest(raw) == expected_sealed_sha256, "original sealed inventory digest changed")
    sealed = decode(raw)
    files = {p.relative_to(directory).as_posix(): p for p in directory.rglob("*") if p.is_file()}
    require(not any(p.is_symlink() for p in directory.rglob("*")), "symlink in retained evidence")
    require(set(files) - {"SEALED.json"} == set(sealed), "retained file inventory differs")
    for name, expected in sealed.items():
        data = files[name].read_bytes()
        require(len(data) == expected["bytes"] and digest(data) == expected["sha256"], "original file changed: " + name)
    report = decode(files["RESULT.json"].read_bytes())
    if report.get("status") == "passed":
        for row in report.get("native_invocations", []):
            label = row.get("case")
            require(type(label) is str and label in {p.removesuffix(".receipt.json") for p in sealed if p.endswith(".receipt.json")},
                    "native receipt absent")
            receipt = decode(files[label + ".receipt.json"].read_bytes())
            require(all(row.get(k) == v for k, v in receipt.items()) and
                    set(row) - set(receipt) <= {"produced_sha256", "produced_bytes"}, "original receipt/report differ")
            child = decode(files[label + ".stdout.log"].read_bytes())
            require(all(receipt.get(k) == v for k, v in child.items()), "original child stdout/receipt differ")
            request = decode(files[label + ".request.json"].read_bytes())
            source = files[label + ".input.bin"].read_bytes()
            output = files[label + ".output.bin"].read_bytes()
            require(digest(source) == request["source_sha256"] == row["input_sha256"] and
                    digest(output) == row["output_sha256"], "original source/output bytes differ")
            if label.startswith("compile-"):
                require(digest(output[:row["core_u32"]]) == row["produced_sha256"], "original produced image differs")
        for arm in ARMS:
            require(digest(files[arm + ".so"].read_bytes()) == report["arms"][arm]["shared_sha256"], "original shared image differs")
    result = summarize(report)
    result["original_inventory_sha256"] = expected_sealed_sha256
    result["original_result_sha256"] = digest(files["RESULT.json"].read_bytes())
    result["verified_original_files"] = len(sealed)
    result["original_bytes_checked"] = True
    result["execution_provenance"] = "retained local evidence consistency; hashes do not independently attest execution or billing"
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--campaign", type=Path, required=True)
    parser.add_argument("--expected-sealed-sha256", required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    require(not args.output.resolve().is_relative_to(args.campaign.resolve()), "keep analysis outside sealed campaign")
    result = read_campaign(args.campaign, args.expected_sealed_sha256)
    with args.output.open("x") as output:
        json.dump(result, output, indent=2, sort_keys=True, allow_nan=False)
        output.write("\n")
    print(json.dumps({"acceptance": result["acceptance"], "complete_paired_inventory": result["complete_paired_inventory"],
                      "original_bytes_checked": result["original_bytes_checked"]}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

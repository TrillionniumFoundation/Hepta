#!/usr/bin/env python3
"""Generate or --check the HIA schema/opcode/target/public-ABI contract tables."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from hepta.hia_schema import compatibility_registry

WIRE_BEGIN = "<!-- BEGIN GENERATED HIA COMPATIBILITY -->"
WIRE_END = "<!-- END GENERATED HIA COMPATIBILITY -->"
JSON_PATH = Path("docs/hia-compatibility.v1.json")
MARKDOWN_PATH = Path("docs/HIA_COMPATIBILITY.md")
PROGRAM_PATH = Path("docs/HIA_PROGRAM.md")


def _codes(values):
    return ", ".join("`" + value + "`" for value in values) or "—"


def render_wire_matrix(matrix):
    """The main language document shares the checked registry summary."""
    lines = [WIRE_BEGIN,
             "| Input schema | Verified executable schema | LLVM targets |",
             "| --- | --- | --- |"]
    aliases = {target["target"]: target["target"].split("-", 1)[0]
               for target in matrix["native"]["targets"]}
    for row in matrix["primitive"]:
        lines.append("| `" + row["schema"] + "` | `" + row["schema"]
                     + "` (preserved) | " + _codes(aliases[t] for t in row["llvm_targets"]) + " |")
    for row in matrix["composite"]:
        lines.append("| `" + row["schema"] + "` | `" + row["normalizes_to"]
                     + "` (checked normalization) | " + _codes(aliases[t] for t in row["llvm_targets"]) + " |")
    lines += [WIRE_END]
    return "\n".join(lines)


def render_markdown(matrix):
    native = matrix["native"]
    lines = [
        "# HIA compatibility contract",
        "",
        "Generated by `python tools/check_hia_compatibility.py`; check committed tables with "
        "`python tools/check_hia_compatibility.py --check`.",
        "",
        "The schema registry, opcode catalog, LLVM profile/publication tables and actual wrapper "
        "extension rules supply these values. `tests/test_hia_compatibility.py` checks real "
        "verification, LLVM text emission, normalization and rejection paths without requiring Clang. "
        "Its optional native test also builds v8 objects for every listed target and checks ELF machine, "
        "RV64 ABI flags and symbol inventories. Run that gate with "
        "`HIA_COMPATIBILITY_REQUIRE_NATIVE=1 CLANG=/path/to/clang python -m unittest tests.test_hia_compatibility` "
        "to fail if the actual compiler is unavailable.",
        "",
        "This table records admitted interfaces. It is not a verification receipt, a successful "
        "native compilation, or target execution evidence. AArch64/RV64 execution requires its "
        "own measured qualification receipt; emission support alone does not supply one.",
        "",
        "Machine-readable contract: [hia-compatibility.v1.json](hia-compatibility.v1.json).",
        "",
        "## Core grammar versions",
        "",
        "Primitive inputs preserve their declared schema and canonical executable bytes during "
        "ordinary verification. Features accumulate; function contracts can change without adding opcodes.",
        "",
        "| Core schema | Grammar profile | Instructions | Newly admitted feature(s) |",
        "| --- | --- | --- | --- |",
    ]
    previous_features = set()
    for row in matrix["primitive"]:
        features = set(row["features"])
        new_features = sorted(features - previous_features)
        lines.append("| `" + row["schema"] + "` | `" + row["profile"] + "` | "
                     + str(len(row["instructions"])) + " | "
                     + (_codes(new_features) if new_features else "Typed scalar SSA, byte owners and loans") + " |")
        previous_features = features
    lines += ["", "Each JSON row includes every admitted instruction, terminator and type plus the "
              "complete opcode catalog hash. The [opcode reference](HIA_OPCODE_REFERENCE.md) describes "
              "operands, results, effects and dynamic checks. Opcode membership grants no public native ABI.",
              "", "## Nominal grammar versions", "",
              "| Input schema | Grammar profile | Exact normalization | Nominal operations |",
              "| --- | --- | --- | --- |"]
    for row in matrix["composite"]:
        lines.append("| `" + row["schema"] + "` | `" + row["profile"] + "` | `"
                     + row["normalizes_to"] + "` | " + _codes(row["nominal_operations"]) + " |")
    legacy = matrix["legacy_nominal"]
    lines += ["", "`CANONICAL_CORE_SCHEMA` remains `" + matrix["canonical_core_schema"]
              + "`; `LATEST_CORE_SCHEMA` is `" + matrix["latest_core_schema"]
              + "`. Composite normalization uses its exact registry mapping, with no implicit upgrade.",
              "", "The historical nominal spelling `" + legacy["schema"]
              + "` has no implicit dispatch. Its explicit `" + legacy["explicit_adapter"]
              + "` adapter separately checks the old grammar and normalizes it to `"
              + legacy["normalizes_to"] + "`.",
              "", "## Native target and publication matrix", "",
              "| Target | LLVM Core schemas | Publication kinds | Additional compiler flags | Shared-library host |",
              "| --- | --- | --- | --- | --- |"]
    for row in native["targets"]:
        lines.append("| `" + row["target"] + "` | " + _codes(row["profiles"])
                     + " | " + _codes(row["publication_kinds"]) + " | "
                     + _codes(row["compiler_flags"]) + " | "
                     + (_codes([row["shared_publication_host"]]) if row["shared_publication_host"] else "Not admitted") + " |")
    build = native["native_build"]
    lines += ["", "Compilation requires actual " + build["compiler"] + " "
              + str(build["minimum_major_version"]) + "+ on a " + build["host_requirements"]
              + ". Admitted build hosts: " + _codes(build["host_targets"]) + ". "
              "Object output can target another architecture; its receipt still distinguishes compilation from execution.",
              "", "Every listed target admits primitive v8 and composite v4 through checked v8 normalization. "
              "Returned owners/loans and nominal values remain internal; this does not add a borrowed-result C ABI.",
              "", "## Public scalar input and output ABI", "",
              "The public C-compatible entry accepts the integer and boolean types below and returns at most "
              "one scalar. The table gives the LLVM extension attribute for **both the argument and result** "
              "of that type. `none` means no LLVM `signext`/`zeroext` attribute; it does not promise that "
              "unused hardware register bits have a value.",
              "",
              "| HIA type | LLVM value | x86-64 argument / result | AArch64 argument / result | RV64 argument / result |",
              "| --- | --- | --- | --- | --- |"]
    target_abi = [{row["type"]: row for row in target["scalar_abi"]}
                  for target in native["targets"]]
    for typ in native["public_entry"]["argument_types"]:
        cells = []
        for abi in target_abi:
            row = abi[typ]
            cells.append("`" + row["argument_extension"] + "` / `" + row["result_extension"] + "`")
        lines.append("| `" + typ + "` | `" + target_abi[0][typ]["llvm_type"] + "` | " + " | ".join(cells) + " |")
    lines += ["", "`usize`/`isize` are 64-bit in this closed word model. RV64 `u32` uses `signext`, "
              "matching the LP64D convention that extends 32-bit integer values to XLEN with bit 31. "
              "AArch64 emits no narrow-argument/result extension attributes.",
              "", "| Interface shape | Native wrapper behavior |", "| --- | --- |",
              "| No result, or one `unit` result | Returns LLVM `void` |",
              "| `unit` argument | No public wrapper |",
              "| Two or more results | No public wrapper |",
              "| Owner, loan, chain, nominal record/enum/task argument or result | No public wrapper |",
              "| `unit` argument or multiple scalar results in an explicit Core `exports` list | Whole native emission rejects with `E_HIA_PROGRAM_ABI` |",
              "| Resource descriptor in an explicit Core `exports` list | Core verification rejects with `E_HIA_TYPE` before emission |",
              "| Unsupported implicit entry | Omitted; at least one and at most 128 representable scalar entries are required |",
              "", "Private calls may use resource values and multiple results when the independent Core verifier "
              "admits them. Host wrappers must retain the exact scalar widths, boolean contract, allocation "
              "and trap boundary; generated metadata never permits constructing ownership or loan descriptors.",
              "", "## Contract identity", "",
              "`compatibility_sha256`: `" + matrix["compatibility_sha256"] + "`", ""]
    return "\n".join(lines)


def expected_files(root=ROOT):
    matrix = compatibility_registry()
    program = (root / PROGRAM_PATH).read_text(encoding="utf-8")
    if program.count(WIRE_BEGIN) != 1 or program.count(WIRE_END) != 1:
        raise ValueError("HIA_PROGRAM.md requires one generated compatibility marker pair")
    start, end = program.index(WIRE_BEGIN), program.index(WIRE_END) + len(WIRE_END)
    if start >= end - len(WIRE_END):
        raise ValueError("HIA_PROGRAM.md compatibility markers are out of order")
    return {
        JSON_PATH: json.dumps(matrix, indent=2, sort_keys=True) + "\n",
        MARKDOWN_PATH: render_markdown(matrix),
        PROGRAM_PATH: program[:start] + render_wire_matrix(matrix) + program[end:],
    }


def main(argv=None, *, root=ROOT):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="reject missing or stale committed tables without writing")
    args = parser.parse_args(argv)
    try:
        outputs = expected_files(root)
    except (OSError, ValueError) as error:
        print("HIA compatibility contract: " + str(error), file=sys.stderr)
        return 1
    stale = []
    for relative, text in outputs.items():
        path = root / relative
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(relative.as_posix())
        else:
            path.write_text(text, encoding="utf-8")
    if stale:
        print("HIA compatibility drift: " + ", ".join(stale), file=sys.stderr)
        return 1
    print("HIA compatibility checked" if args.check else "HIA compatibility generated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

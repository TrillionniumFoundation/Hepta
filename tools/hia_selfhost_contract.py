def file_digests(root=ROOT):
    root = Path(root)
    # Include the complete Python seed package, not a hand-maintained subset
    # that can omit a transitively imported checker or native ABI dependency.
    # The v9 shadow/resource implementation is separately executed by Cargo;
    # retain its complete Rust source and dependency locks, not just new tests.
    shadow = root / "rust/hia-core-shadow"
    paths = sorted(set(SOURCE_FILES) | {
        p.relative_to(root).as_posix() for p in (root / "hepta").rglob("*.py")
    } | {
        p.relative_to(root).as_posix() for p in shadow.rglob("*.rs")
    } | {
        (shadow / name).relative_to(root).as_posix() for name in ("Cargo.toml", "Cargo.lock")
    })
    return {path: sha256((root / path).read_bytes()).hexdigest() for path in paths}



def _native_worker_helper_count(root):
    path = Path(root) / 'hepta/hia_native_helpers.py'
    declarations = [
        node for node in ast.parse(path.read_bytes(), filename=str(path)).body
        if isinstance(node, ast.Assign)
        and any(isinstance(target, ast.Name) and target.id == 'HELPERS'
                for target in node.targets)
    ]
    if (len(declarations) != 1 or len(declarations[0].targets) != 1
            or not isinstance(declarations[0].value, ast.Dict)):
        raise ValueError('native helper registry must have one literal HELPERS declaration')
    table = declarations[0].value
    # The admitted registry is a flat string-to-two-strings table. Reading
    # those AST constants directly avoids ast.literal_eval's recursive local
    # function/cell cycles on every ordinary source-contract validation.
    # All other syntax retains the original evaluator and rejection behavior.
    helpers = {}
    for key, value in zip(table.keys, table.values):
        if (not isinstance(key, ast.Constant) or type(key.value) is not str
                or not isinstance(value, ast.Tuple) or len(value.elts) != 2
                or not isinstance(value.elts[0], ast.Constant)
                or type(value.elts[0].value) is not str
                or not isinstance(value.elts[1], ast.Constant)
                or type(value.elts[1].value) is not str):
            helpers = ast.literal_eval(table)
            break
        helpers[key.value] = (value.elts[0].value, value.elts[1].value)
    if (type(helpers) is not dict or len(helpers) != len(table.keys)
            or any(type(selector) is not str
                   or not selector.startswith('HEPTA_HIA_')
                   or not selector.endswith('_MANIFEST')
                   or type(contract) is not tuple or len(contract) != 2
                   or any(type(name) is not str or not name.isidentifier()
                          for name in contract)
                   for selector, contract in helpers.items())):
        raise ValueError('native helper registry has duplicate or invalid literal contracts')
    return len(helpers)


"""Generate one exact HIA owner and its fixed CPython operand inventory."""
from __future__ import annotations
import argparse
from hashlib import sha256
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
if __package__ in (None, ''):
    sys.path.insert(0, str(ROOT))

from hepta.hia_agent_assembly import render_assembly
from tools.hia_front_control import compile_policy
from tools.hia_front_generator import document as _document, ports_source
from tools.generate_hia_machine_plan_control import table

ENTRIES = ('_reject', 'verify_program')
IMPORTS = {'hia_program_composite': ('elaborate_program',), 'hia_core_admission_native': ('selected_core_structure',)}

def program():
    return compile_policy((ROOT / 'tools/hia_core_verification_policy.py').read_text(), ENTRIES, IMPORTS)

def document(policy=None):
    return _document(program() if policy is None else policy, 'core_verification')

def generated():
    policy = program()
    data = table(policy)
    return (render_assembly(document(policy)).encode('utf-8'),
            ports_source(policy, data, ENTRIES, IMPORTS).encode('utf-8'), policy, data)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'examples/hia_bootstrap/core_verification.hepta')
    parser.add_argument('--ports', type=Path, default=ROOT / 'hepta/hia_core_verification_ports.py')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    assembly, ports, policy, data = generated()
    if args.check:
        if args.output.read_bytes() != assembly or args.ports.read_bytes() != ports:
            raise AssertionError('core_verification generated bytes differ')
    else:
        args.output.write_bytes(assembly)
        args.ports.write_bytes(ports)
    print({'roots': len(ENTRIES), 'functions': len(policy.functions),
           'instructions': sum(len(f.instructions) for f in policy.functions),
           'table_bytes': len(data), 'table_sha256': sha256(data).hexdigest(),
           'source_sha256': sha256(assembly).hexdigest(),
           'ports_sha256': sha256(ports).hexdigest(), 'whole_normalization_closed': False})

if __name__ == '__main__':
    main()

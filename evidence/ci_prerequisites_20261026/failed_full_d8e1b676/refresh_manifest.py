#!/usr/bin/env python3
"""Bind the evidence appendix's exact sidecar inventory without executing inputs."""
import argparse
import hashlib
import json
from pathlib import Path


def refresh(directory):
    archive = json.loads((directory / "run-artifacts.manifest.json").read_bytes())
    parts = [row["path"] for row in archive["parts"]]
    files = {}
    for path in sorted(directory.rglob("*")):
        if path.is_dir():
            continue
        assert path.is_file() and not path.is_symlink(), "nonregular evidence sidecar"
        name = path.relative_to(directory).as_posix()
        assert "__pycache__" not in path.parts, "unintended generated bytecode"
        if name == "MANIFEST.json" or name in parts:
            continue
        raw = path.read_bytes()
        files[name] = {"bytes": len(raw), "sha256": hashlib.sha256(raw).hexdigest()}
    value = {"schema": "hepta.ci-candidate.bundle.v1", "source_commit": archive["source_commit"],
        "files": files, "archive_parts": parts,
        "original_zip": json.loads((directory / "zip-identity.json").read_bytes()),
        "scope": "exact appendix inventory; integrity is anchored by the evidence Git commit, not by a self-signed manifest"}
    (directory / "MANIFEST.json").write_text(json.dumps(value, indent=2, sort_keys=True) + "\n")
    return {"sidecar_files": len(files), "archive_parts": len(parts), "source_commit": value["source_commit"]}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--directory", type=Path, default=Path(__file__).resolve().parent)
    args = parser.parse_args()
    print(json.dumps(refresh(args.directory), indent=2, sort_keys=True))

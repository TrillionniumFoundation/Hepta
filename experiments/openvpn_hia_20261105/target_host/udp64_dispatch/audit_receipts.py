"""Read-only audit of one fixed failed artifact. Does not extract or execute it."""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import zipfile

ARCHIVE_SHA256 = '0c4121ab9ff0467f67986a89aeb858345a2f0edbda7e0d26a323ab27234a43ba'
SOURCE = '1a9deb8ea58b9091e7b9179cae87d9f93eef4c35'


def audit(path):
    digest = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for chunk in iter(lambda: stream.read(1048576), b''):
            digest.update(chunk)
    if digest.hexdigest() != ARCHIVE_SHA256:
        raise ValueError('not the pinned artifact; no other artifact is interpreted')
    with zipfile.ZipFile(path) as archive:
        names = archive.namelist()
        if len(names) != len(set(names)) or len(names) != 11225:
            raise ValueError('unexpected or duplicate artifact member inventory')
        def read(name):
            raw = archive.read(name)
            return json.loads(raw), hashlib.sha256(raw).hexdigest()
        build, build_hash = read('build.json')
        report, report_hash = read('tunnel/target-result.json')
        if build['hepta_commit'] != SOURCE or report['complete'] is not False:
            raise ValueError('wrong source or outcome')
        workloads = report['plan']['performance']['workloads']
        inventory, udp = [], []
        cases = [c for c in report['cases'] if c['kind'] == 'performance']
        for case in cases:
            for index, work in enumerate(workloads):
                member = f"tunnel/cases/{case['id']}/workload-{index}-{work['name']}-measurement.json"
                row = {'case': case['id'], 'arm': case['arms']['client'], 'workload': work['name'],
                       'original_case_status': case['status'], 'member': member}
                if member not in names:
                    if case['status'] != 'planned' or case.get('receipt'):
                        raise ValueError('missing measurement for an attempted case')
                    row.update(outcome='unattempted', measurement_exists=False,
                               basis='original case is planned and has no case or measurement receipt')
                    inventory.append(row)
                    continue
                measurement, member_hash = read(member)
                row.update(measurement_exists=True, measurement_sha256=member_hash, original_status=measurement['status'],
                           passed=measurement['passed'], failures=measurement.get('failures', []))
                # Planned-but-never-started receipts are actual source records,
                # not zeros or invented measurements.
                if measurement['status'] == 'unattempted':
                    row['outcome'] = 'unattempted'
                else:
                    row['outcome'] = 'completed' if measurement['passed'] else 'failed'
                inventory.append(row)
                if work['name'] != 'udp-64' or row['outcome'] == 'unattempted':
                    continue
                client, server = measurement['client_iperf'], measurement['server_iperf']
                link = measurement['path_delta']['client']['link_delta']
                # Last sender interval with nonzero generated bytes, not a
                # throughput estimate from the aborted end summary.
                sender_end = max(i['sum']['end'] for i in client['intervals'] if i['sum']['bytes'] > 0)
                last_client_interval = client['intervals'][-1]['sum']
                last_server_sender_interval = server['intervals'][-1]['sum_bidir_reverse']
                udp.append({
                    'case': case['id'], 'arm': case['arms']['client'], 'passed': measurement['passed'],
                    'measurement_sha256': member_hash, 'member': member,
                    'requested_seconds': measurement['duration_requested_seconds'],
                    'measurement_elapsed_seconds': measurement['elapsed_seconds'],
                    'client_process_elapsed_seconds': measurement['client_process']['elapsed_seconds'],
                    'server_process_elapsed_seconds': measurement['server_process']['elapsed_seconds'],
                    'client_timed_out': measurement['client_process'].get('timed_out', False),
                    'server_timed_out': measurement['server_process'].get('timed_out', False),
                    'client_last_nonzero_sender_interval_end': sender_end,
                    'client_final_sender_interval': {k: last_client_interval[k] for k in ('start', 'end', 'bytes')},
                    'server_last_interval_end': server['intervals'][-1]['sum']['end'],
                    'server_final_sender_interval': {k: last_server_sender_interval[k] for k in ('start', 'end', 'bytes')},
                    'server_local_received_bytes': server['end']['sum_received']['bytes'],
                    'client_tun_tx_packets_delta': link['tx']['packets'],
                    'client_tun_tx_dropped_delta': link['tx']['dropped'],
                    'client_tun_rx_packets_delta': link['rx']['packets'],
                    'client_tx_queue_length': measurement['path_before']['client']['link']['txqlen'],
                    'client_reverse_loss_percent': client['end']['sum_received_bidir_reverse']['lost_percent'],
                    'same_authenticated_sessions': measurement['checks']['same_authenticated_sessions'],
                    'local_receiver_summary_warning': 'aborted observations are not qualified throughput' if not measurement['passed'] else 'partial matrix observation only',
                })
        outcomes = dict(Counter(row['outcome'] for row in inventory))
        if len(inventory) != 216 or outcomes != {'failed': 29, 'completed': 139, 'unattempted': 48}:
            raise ValueError('full fixed inventory differs from the reported failed run')
        return {
            'schema': 'hepta.openvpn-hia.udp64-readonly-diagnosis.v1',
            'artifact_url': 'https://github.com/TrillionniumFoundation/Hepta/actions/runs/42033735657/artifacts/13448779084',
            'archive_sha256': ARCHIVE_SHA256, 'archive_members': len(names),
            'hepta_source': SOURCE, 'build_receipt_sha256': build_hash,
            'target_receipt_sha256': report_hash, 'original_complete': report['complete'],
            'original_elapsed_seconds': report['elapsed_seconds'], 'original_counts': report['counts'],
            'original_gates': report['gates'],
            'performance_case_statuses': dict(Counter(case['status'] for case in cases)),
            'workload_outcomes': outcomes, 'fixed_workload_inventory': inventory, 'udp64_attempts': udp,
            'claim_limit': 'Original failures and unattempted samples retained. No causal target proof, throughput advantage, rerun, or reclassification.',
        }


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('artifact', type=Path)
    args = parser.parse_args()
    print(json.dumps(audit(args.artifact), indent=2, sort_keys=True))

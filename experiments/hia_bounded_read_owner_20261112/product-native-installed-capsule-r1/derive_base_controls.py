def once(text, old, new):
    assert text.count(old) == 1, (old[:100], text.count(old))
    return text.replace(old, new, 1)


def definition(text, name, replacement):
    node, = [x for x in ast.parse(text).body if isinstance(x, ast.FunctionDef) and x.name == name]
    start = min([node.lineno, *(x.lineno for x in node.decorator_list)])
    lines = text.splitlines(keepends=True)
    return ''.join(lines[:start-1]) + replacement.rstrip() + '\n' + ''.join(lines[node.end_lineno:])


